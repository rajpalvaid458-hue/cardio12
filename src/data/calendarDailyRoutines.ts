// Helper: Get routine for any date string (YYYY-MM-DD)
export function getRoutineForDateKey(dateKey: string, splitType: CalendarSplitType = 'bro_split'): DayOfWeekRoutine {
  try {
    const d = new Date(dateKey + 'T00:00:00');
    let day = d.getDay(); // 0 = Sunday, 1 = Monday, ..., 6 = Saturday
    const dayIndex = day === 0 ? 7 : day;
    return BRO_SPLIT_ROUTINE[dayIndex] || BRO_SPLIT_ROUTINE[1];
  } catch {
    return BRO_SPLIT_ROUTINE[1];
  }
}

// Convert Day Routine to an executable WorkoutPlan
export function convertDayRoutineToWorkoutPlan(routine: DayOfWeekRoutine, dateKey?: string): WorkoutPlan {
  const planExercises: WorkoutExerciseItem[] = routine.exercises.map((ex, idx) => ({
    id: `plan_ex_${routine.dayIndex}_${idx}_${Date.now()}`,
    exerciseId: ex.exerciseId,
    name: ex.name,
    targetMuscle: ex.targetMuscle,
    category: ex.category,
    equipment: ex.equipment,
    restSec: ex.restSeconds,
    formTip: ex.formTip,
    sets: Array.from({ length: ex.defaultSets }).map((_, sIdx) => ({
      id: `s_${idx}_${sIdx}`,
      setNumber: sIdx + 1,
      weightKg: 0,
      reps: parseInt(ex.defaultReps.split('-')[0], 10) || 10,
      completed: false,
      isWarmup: sIdx === 0 && ex.defaultSets >= 4,
    })),
  }));

  return {
    id: `routine-day-${routine.dayIndex}-${dateKey || 'today'}`,
    title: routine.titleEn,
    splitType: routine.titleEn,
    level: 'intermediate',
    targetGender: 'all',
    durationMinutes: routine.estimatedDurationMins,
    daysPerWeek: 5,
    description: routine.taglineEn,
    tags: [routine.dayNameEn, 'Calendar Routine', routine.focusMuscleEn],
    exercises: planExercises,
    programType: 'daily',
  };
}

// Convert Day Routine to an instant completed log
export function convertDayRoutineToCompletedLog(routine: DayOfWeekRoutine, dateKey: string): CompletedWorkoutLog {
  return {
    id: `log_calendar_${Date.now()}_${Math.random().toString(36).substr(2, 5)}`,
    title: routine.titleEn,
    date: new Date(dateKey + 'T10:00:00').toISOString(),
    durationSeconds: routine.estimatedDurationMins * 60,
    totalVolumeKg: routine.isRestDay ? 0 : 1250,
    completedSetsCount: routine.exercises.reduce((acc, ex) => acc + ex.defaultSets, 0),
    caloriesBurned: routine.estimatedCalories,
    exercises: routine.exercises.map((ex) => ({
      name: ex.name,
      targetMuscle: ex.targetMuscle,
      completedSets: Array.from({ length: ex.defaultSets }).map(() => ({
        weightKg: routine.isRestDay ? 0 : 20,
        reps: parseInt(ex.defaultReps.split('-')[0], 10) || 12,
        isWarmup: false,
      })),
    })),
    rpeAverage: routine.isRestDay ? 3 : 8,
    notes: `Completed scheduled ${routine.dayNameEn} (${routine.focusMuscleEn}) session via Training Calendar.`,
  };
}

// Find matched Exercise from EXERCISE_DATABASE
export function findExerciseInDatabase(exName: string, category?: string): Exercise | null {
  const norm = exName.toLowerCase();
  const match = EXERCISE_DATABASE.find((e) => {
    const eNorm = e.name.toLowerCase();
    return norm.includes(eNorm) || eNorm.includes(norm);
  });
  if (match) return match;

  // Fallback match on category
  if (category) {
    const catMatch = EXERCISE_DATABASE.find((e) => e.category === category);
    if (catMatch) return catMatch;
  }

  return null;
}
